function configure_noise_profile(modelName)
filterMask = Simulink.Mask.get([modelName '/Bo_Loc_Wavelet_DWT_Wiener']);
if isempty(filterMask.getParameter('Noise_Start_Auto'))
    filterMask.addParameter('Name','Noise_Start_Auto','Value','1', ...
        'Prompt','Skip constant recorder startup for noise profile (1=auto, 0=manual)');
end
if isempty(filterMask.getParameter('Noise_Start'))
    filterMask.addParameter('Name','Noise_Start','Value','0', ...
        'Prompt','Manual noise-profile start in seconds (Noise_Start_Auto=0)');
end
initialization = filterMask.Initialization;
if contains(initialization,'Noise_Profile_Start_Sample')
    return;
end
startMarker = '[x_calib, Fs_calib] = audioread(inFile);';
endMarker = 'Pn_vec = zeros(1, 8);';
startPosition = strfind(initialization,startMarker);
endPosition = strfind(initialization,endMarker);
assert(isscalar(startPosition) && isscalar(endPosition) && startPosition<endPosition, ...
    'WaveletDSP:MaskLayout','Noise calibration code did not match; model was not saved.');
profileCode = strjoin({ ...
    '[x_calib, Fs_calib] = audioread(inFile);', ...
    'validateattributes(Noise_Sec,{''double''},{''scalar'',''real'',''finite'',''positive''});', ...
    'validateattributes(Noise_Start,{''double''},{''scalar'',''real'',''finite'',''nonnegative''});', ...
    'validateattributes(Noise_Start_Auto,{''double''},{''scalar'',''binary''});', ...
    'assert(size(x_calib,2)==1 && all(isfinite(x_calib(:))), ''WaveletDSP:InvalidNoiseProfile'', ''Noise profiling requires finite mono audio.'');', ...
    'N_n = floor(Noise_Sec*Fs_calib);', ...
    'Startup_Skipped_Samples = 0;', ...
    'if Noise_Start_Auto==1', ...
    '    firstChanged = find(x_calib~=x_calib(1),1,''first'');', ...
    '    assert(~isempty(firstChanged), ''WaveletDSP:ConstantRecording'', ''Recording is entirely constant. Record real background noise before speech, or provide manual noise powers.'');', ...
    '    if firstChanged-1>=ceil(0.010*Fs_calib)', ...
    '        Startup_Skipped_Samples = firstChanged-1;', ...
    '    end', ...
    '    Noise_Profile_Start_Sample = Startup_Skipped_Samples+1;', ...
    'else', ...
    '    Noise_Profile_Start_Sample = floor(Noise_Start*Fs_calib)+1;', ...
    'end', ...
    'Noise_Profile_End_Sample = Noise_Profile_Start_Sample+N_n-1;', ...
    'assert(N_n>=1024 && Noise_Profile_End_Sample<=numel(x_calib), ''WaveletDSP:InvalidNoiseProfile'', ''Selected profile needs at least 1024 samples and must fit after the chosen start; shorten Noise_Sec or choose another Noise_Start.'');', ...
    'noiseProfile = x_calib(Noise_Profile_Start_Sample:Noise_Profile_End_Sample);', ...
    'assert(var(noiseProfile,1)>eps(max(abs(noiseProfile)))^2, ''WaveletDSP:ConstantNoiseProfile'', ''Selected noise profile is constant or numerically constant. Enable Noise_Start_Auto or choose a real noise-only interval using Noise_Start.'');', ...
    'fprintf(''Noise profile: start=%.9f s, duration=%.9f s, skipped constant startup=%d samples. This is not a speech detector.\n'', (Noise_Profile_Start_Sample-1)/Fs_calib,N_n/Fs_calib,Startup_Skipped_Samples);', ...
    '[C_n, L_n] = wavedec(noiseProfile, lev, wname, ''Mode'', ''sym'');', ...
    },newline);
