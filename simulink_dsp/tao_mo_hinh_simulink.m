treeDelays=[1827 899 435 203 87 29 0 0]+(commonDelay-syncDelays.*2.^levels)./2.^levels;
for bandIndex=1:8
    kinds={'sync','pow','sm','tree'};
    counts=[syncDelays(bandIndex) powerLengths(bandIndex) smoothLengths(bandIndex) treeDelays(bandIndex)];
    for kindIndex=1:4
        numeric_fir(role_block(modelName,sprintf('%s_%d',kinds{kindIndex},bandIndex)), ...
            counts(kindIndex),ismember(kinds{kindIndex},{'pow','sm'}));
    end
end
totalDelay=29*(2^7-1)+commonDelay;
numeric_fir(role_block(modelName,'reference_sync'),totalDelay,false);
numeric_fir(role_block(modelName,'noisy_sync'),totalDelay,false);
set_param(modelName,'InitFcn',model_initialization(),'StopFcn',model_export());
vietnamese_labels(modelName,false,true);
end

function numeric_fir(block,count,isAverage)
blockMask=Simulink.Mask.get(block);
if isempty(blockMask)
    blockMask=Simulink.Mask.create(block);
end
if isAverage
    prompt='Số mẫu cửa sổ (tự tính từ thiết lập bộ lọc)';
    coefficients='ones(1,Sample_Count)/Sample_Count';
    blockMask.Description='Trung bình các mẫu trong cửa sổ. Chỉnh thời gian cửa sổ tại bộ lọc; không cần nhập dãy hệ số.';
else
    prompt='Số mẫu đồng bộ (tự tính từ cấu trúc và thiết lập bộ lọc)';
    coefficients='[zeros(1,Sample_Count) 1]';
    blockMask.Description='Đồng bộ tín hiệu theo số mẫu. Giá trị được tính tự động để giữ nguyên phép lọc; không cần nhập dãy hệ số.';
end
parameter=blockMask.getParameter('Sample_Count');
if isempty(parameter)
    parameter=blockMask.addParameter('Name','Sample_Count','Prompt',prompt,'Value',sprintf('%.0f',count));
else
    parameter.Value=sprintf('%.0f',count);
end
parameter.Enabled='off';
blockMask.Initialization=sprintf('validateattributes(Sample_Count,{''double''},{''scalar'',''integer'',''finite'',''>='',%d});',double(isAverage));
set_param(block,'Coefficients',coefficients);
end

function text=translate_text(text,names,messages,reverse)
for nameIndex=1:size(names,1)
    if reverse, before=names{nameIndex,2}; after=names{nameIndex,1}; else, before=names{nameIndex,1}; after=names{nameIndex,2}; end
    escaped=regexptranslate('escape',before);
    text=regexprep(text,['/' escaped '(?=[/''\]])'],['/' after]);
    text=strrep(text,['''' before '/'],['''' after '/']);
    text=strrep(text,['''''' before '/'],['''''' after '/']);
end
for messageIndex=1:size(messages,1)
    if reverse, text=strrep(text,messages{messageIndex,2},messages{messageIndex,1}); else, text=strrep(text,messages{messageIndex,1},messages{messageIndex,2}); end
end
end

function blocks=project_blocks(systemPath)
blocks=find_system(systemPath,'SearchDepth',1,'LookUnderMasks','all','FollowLinks','off','Type','Block');
children=blocks;
for blockIndex=1:numel(children)
    block=children{blockIndex};
    if strcmp(block,systemPath), continue; end
    if strcmp(get_param(block,'BlockType'),'SubSystem') && strcmp(get_param(block,'LinkStatus'),'none')
        nested=project_blocks(block);
        blocks=[blocks; nested(~strcmp(nested,block))];
    end
end
end
