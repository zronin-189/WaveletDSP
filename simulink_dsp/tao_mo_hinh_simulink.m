% TAO_MO_HINH_SIMULINK
% Khoi tao mo hinh Simulink chuyen sau cho thuat toan khu nhieu Wavelet DWT + Wiener
% Duong loc dung native blocks; uoc luong Pn van nam trong Mask Initialization.
%
% MO HINH KHONG CAN CHAY SCRIPT .m BEN NGOAI:
% - Khong phu thuoc bat ky script .m nao ben ngoai, mo file .slx va bam Run la chay.
% - 0 khoi MATLAB Function, 0 khoi Delay z^-A (Phuong an 3: Discrete FIR Filter).
% - Tich hop Cai tien 1: Bo do chi so Live SNR (In, Out, Delta) & RMSE truc tiep bang Display blocks.
% - Time Scope 2 kenh doi chieu dang song; xuat WAV truc tiep tu nhanh denoised.

function tao_mo_hinh_simulink(modelName, updateOnly)
projectFolder = fileparts(fileparts(mfilename('fullpath')));
modelFolder = fileparts(mfilename('fullpath'));
if nargin == 0
    modelName = 'mo_hinh_dwt_wiener';
end
if nargin >= 2 && updateOnly
    load_system(fullfile(modelFolder, [modelName '.slx']));
    assert(strcmp(get_param(modelName,'Dirty'),'off'), ...
        'WaveletDSP:UnsavedModel','Hãy lưu các chỉnh sửa mô hình trước khi cập nhật.');
    backupDirectory = fullfile(projectFolder,'.agent-tmp');
    if ~isfolder(backupDirectory), mkdir(backupDirectory); end
    copyfile(get_param(modelName,'FileName'),fullfile(backupDirectory, ...
        ['before_optional_clean_' char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')) '.slx']));
    roles=find_system(modelName,'LookUnderMasks','all','FollowLinks','off','RegExp','on','Tag','^WaveletDSP:');
    if ~isempty(roles)
        configure_numeric_interface(modelName);
        save_system(modelName);
        return;
    end
    vietnamese_labels(modelName,true);
    rename_user_blocks(modelName);
    configure_optional_reference(modelName);
    configure_noise_profile(modelName);
    simplify_meter(modelName);
    set_param(modelName,'InitFcn',model_initialization(),'StopFcn',model_export());
    vietnamese_labels(modelName,false);
    configure_numeric_interface(modelName);
    save_system(modelName);
    return;
end

if bdIsLoaded(modelName)
    assert(strcmp(get_param(modelName, 'Dirty'), 'off'), ...
        'WaveletDSP:UnsavedModel', 'Hãy lưu các chỉnh sửa mô hình trước khi dựng lại.');
    close_system(modelName, 0);
end
if isfile(fullfile(modelFolder, [modelName '.slx']))
    backupDirectory = fullfile(projectFolder, '.agent-tmp');
    if ~isfolder(backupDirectory), mkdir(backupDirectory); end
    copyfile(fullfile(modelFolder, [modelName '.slx']), fullfile(backupDirectory, ...
        [modelName '_' char(datetime('now', 'Format', 'yyyyMMdd_HHmmss_SSS')) '.slx']));
end

load_system('simulink');
load_system('dspxfrm3');
load_system('dspsrcs4');
load_system('dspsnks4');
load_system('dsparch4');
load_system('dspstat3');

input_audio_file = fullfile(projectFolder, 'data_DSP_speech', 'noisy', 'pink_10db', 'speech_001_pink_10dB.wav');
clean_audio_file = fullfile(projectFolder, 'data_DSP_speech', 'clean', 'speech_001.wav');
output_audio_file = fullfile(projectFolder, 'results', 'simulink_denoised_output.wav');
if ~exist(fullfile(projectFolder, 'results'), 'dir'), mkdir(fullfile(projectFolder, 'results')); end

[x_init, fs] = audioread(input_audio_file);
N_frame = 1024; % Khung xu ly 1024 mau (boi so cua 2^7 = 128)

% 1. Tao Model moi
new_system(modelName);

set_param(modelName, 'SolverType', 'Fixed-step');
set_param(modelName, 'Solver', 'FixedStepDiscrete');
set_param(modelName, 'FixedStep', sprintf('1/%d', fs));
set_param(modelName, 'StopTime', '4');
set_param(modelName, 'InitFcn', model_initialization());
set_param(modelName, 'StopFcn', model_export());

% 2. Khoi Nguon Am thanh co nhieu (Noisy)
srcBlock = [modelName, '/Noisy'];
add_block('dspsrcs4/From Multimedia File', srcBlock, ...
    'Position', [30, 80, 210, 140], ...
    'inputFilename', input_audio_file, ...
    'SamplesPerFrame', num2str(N_frame), ...
    'AudioDataType', 'double', ...
    'outputEOF', 'on', ...
    'loop', 'off');

% Khoi Stop Simulation tu dong dung khi doc het file am thanh
stopBlock = [modelName, '/Stop_Simulation'];
add_block('simulink/Sinks/Stop Simulation', stopBlock, ...
    'Position', [240, 115, 275, 145]);
delete_block(stopBlock);
add_block('simulink/Sinks/Terminator', [modelName '/Source_EOF'], ...
    'Position', [240, 115, 275, 145]);
add_line(modelName, 'Noisy/2', 'Source_EOF/1');

% Khoi Nguon Am thanh sach tham chieu (Clean) de do Live SNR / RMSE
cleanBlock = [modelName, '/Clean'];
add_block('dspsrcs4/From Multimedia File', cleanBlock, ...
    'Position', [30, 310, 210, 370], ...
    'inputFilename', clean_audio_file, ...
    'SamplesPerFrame', num2str(N_frame), ...
    'AudioDataType', 'double', ...
    'outputEOF', 'off', ...
    'loop', 'off');

% 3. Subsystem Bo Loc Wavelet DWT + Wiener
subsys = [modelName, '/Bo_Loc_Wavelet_DWT_Wiener'];
add_block('simulink/Ports & Subsystems/Subsystem', subsys, ...
    'Position', [280, 60, 560, 130]);
Simulink.SubSystem.deleteContents(subsys);

% Tao Mask cho Subsystem de tinh toan thong so doc lap trong Simulink
m = Simulink.Mask.create(subsys);
m.Type = 'Bo Loc Wavelet DWT Wiener Full Native';
m.Description = sprintf([...
    'Duong loc Wavelet DWT + Wiener dung native blocks. Pn tinh trong Mask Initialization.\n' ...
    '- KHONG DUNG BAT KY KHOI MATLAB FUNCTION NAO.\n' ...
    '- KHONG DUNG BAT KY KHOI DELAY (z^-A) NAO (Toan bo su dung Bo loc so Discrete FIR Filter).\n' ...
    '- Hoat dong hoan toan doc lap, cho phep dieu chinh moi thong so truc tiep tai Mask.']);

m.addParameter('Prompt', 'Thoi gian lay mau nhieu ban dau Noise_Sec (giay)', ...
    'Name', 'Noise_Sec', 'Value', '0.25');
m.addParameter('Prompt', 'Cua so do cong suat cuc bo Win_Pow (giay)', ...
    'Name', 'Win_Pow', 'Value', '0.064');
m.addParameter('Prompt', 'Cua so lam muot Gain Win_Smooth (giay)', ...
    'Name', 'Win_Smooth', 'Value', '0.040');
m.addParameter('Prompt', 'San Gain toi thieu Gain_Floor (0 < min < 1)', ...
    'Name', 'Gain_Floor', 'Value', '0.05');
m.addParameter('Prompt', 'Automatically match clean to speech_NNN input (1/0)', ...
    'Name', 'Auto_Clean', 'Value', '1');
m.addParameter('Prompt', 'Tu dong do cong suat nhieu tu file dau vao (1 = Bat, 0 = Thu cong)', ...
    'Name', 'Noise_Auto', 'Value', '1');
m.addParameter('Prompt', 'Mang cong suat nhieu 8 dai thu cong (khi Noise_Auto = 0)', ...
    'Name', 'Noise_Powers', 'Value', '[0.000004 0.000008 0.000014 0.000025 0.000055 0.000108 0.000112 0.002000]');

% Mask Initialization Code (chay ben trong Simulink khi nguoi dung thay doi tham so tren GUI)
m.Initialization = sprintf([...
    'inFile = get_param([bdroot ''/Noisy''], ''inputFilename'');\n' ...
    'inputInfo = audioinfo(inFile);\n' ...
    'Fs = inputInfo.SampleRate;\n' ...
    'validateattributes(Win_Pow, {''double''}, {''scalar'',''positive'',''finite''});\n' ...
    'validateattributes(Win_Smooth, {''double''}, {''scalar'',''positive'',''finite''});\n' ...
    'validateattributes(Gain_Floor, {''double''}, {''scalar'',''>='',0,''<='',1});\n' ...
    'wname = ''coif5'';\n' ...
    'lev = 7;\n' ...
    'if Noise_Auto == 1\n' ...
    '        [x_calib, Fs_calib] = audioread(inFile);\n' ...
    '        N_n = floor(Noise_Sec * Fs_calib);\n' ...
    '        assert(size(x_calib,2)==1 && N_n>=1024 && N_n<=numel(x_calib), ''Invalid mono noise profile.'');\n' ...
    '        [C_n, L_n] = wavedec(x_calib(1:N_n), lev, wname, ''Mode'', ''sym'');\n' ...
    '        Pn_vec = zeros(1, 8);\n' ...
    '        for k = 1:7\n' ...
    '            Pn_vec(k) = var(detcoef(C_n, L_n, k), 1);\n' ...
    '        end\n' ...
    '        Pn_vec(8) = var(appcoef(C_n, L_n, wname, 7), 1);\n' ...
    'else\n' ...
    '    Pn_vec = Noise_Powers;\n' ...
    'end\n' ...
    'validateattributes(Pn_vec, {''double''}, {''vector'',''numel'',8,''nonnegative'',''finite''});\n' ...
    'levels = [1, 2, 3, 4, 5, 6, 7, 7];\n' ...
    'delays_tree = [1827, 899, 435, 203, 87, 29, 0, 0];\n' ...
    'window_power = max(1, round(Win_Pow*Fs./2.^levels));\n' ...
    'window_smooth = max(1, round(Win_Smooth*Fs./2.^levels));\n' ...
    'sync_delays = floor((window_power-1)/2)+floor((window_smooth-1)/2);\n' ...
    'common_delay = 128*ceil(max(sync_delays.*2.^levels)/128);\n' ...
    'delays_tree = delays_tree+(common_delay-sync_delays.*2.^levels)./2.^levels;\n' ...
    'for k = 1:8\n' ...
    '    Fs_k = Fs / (2^levels(k));\n' ...
    '    w_pow_k = max(1, round(Win_Pow * Fs_k));\n' ...
    '    w_sm_k = max(1, round(Win_Smooth * Fs_k));\n' ...
    '    d_sync_k = floor((w_pow_k - 1)/2) + floor((w_sm_k - 1)/2);\n' ...
    '    eval(sprintf(''b_pow_%%d = ones(1, %%d)/%%d;'', k, w_pow_k, w_pow_k));\n' ...
    '    eval(sprintf(''b_sm_%%d = ones(1, %%d)/%%d;'', k, w_sm_k, w_sm_k));\n' ...
    '    eval(sprintf(''b_sync_%%d = [zeros(1, %%d), 1];'', k, d_sync_k));\n' ...
    '    eval(sprintf(''b_tree_%%d = [zeros(1, %%d), 1];'', k, delays_tree(k)));\n' ...
    '    eval(sprintf(''Pn_%%d = %%.12e;'', k, Pn_vec(k)));\n' ...
    'end\n' ...
]);

% Them cong In1 va Out1 cho Subsystem
add_block('simulink/Sources/In1', [subsys, '/u_in'], 'Position', [40, 200, 70, 215]);
add_block('simulink/Sinks/Out1', [subsys, '/y_out'], 'Position', [920, 200, 950, 215]);

% Khoi DWT & IDWT thuan tu DSP System Toolbox
add_block('dspxfrm3/DWT', [subsys, '/DWT'], ...
    'Position', [120, 50, 200, 370], ...
    'Wname', 'Coiflets', 'Order', '5', 'NumLevels', '7', 'tree', 'Asymmetric', 'Output', 'Multiple ports');
add_line(subsys, 'u_in/1', 'DWT/1');

add_block('dspxfrm3/IDWT', [subsys, '/IDWT'], ...
    'Position', [650, 50, 730, 370], ...
    'Wname', 'Coiflets', 'Order', '5', 'NumLevels', '7', 'tree', 'Asymmetric', 'Input', 'Multiple ports');

% Mang tre bu pha da toc do tren cay IDWT
delays_tree = [1827, 899, 435, 203, 87, 29, 0, 0];

% Tao 8 Subsystem loc Wiener cho 8 dai con bang khoi toan hoc thuan
for i = 1:8
    sb = sprintf('%s/Subband_%d', subsys, i);
    add_block('simulink/Ports & Subsystems/Subsystem', sb, ...
        'Position', [260, 40 + (i-1)*45, 380, 75 + (i-1)*45]);
    Simulink.SubSystem.deleteContents(sb);
    
    add_block('simulink/Sources/In1', [sb, '/in'], 'Position', [20, 60, 50, 75]);
    add_block('simulink/Sinks/Out1', [sb, '/out'], 'Position', [740, 60, 770, 75]);
    
    % Cong thuc 1: Dong bo tin hieu (FIR Filter: b = [zeros(1, d_sync), 1])
    add_block('dsparch4/Discrete FIR Filter', [sb, '/FIR_Sync'], ...
        'Position', [100, 50, 160, 85], ...
        'Coefficients', sprintf('b_sync_%d', i));
    add_line(sb, 'in/1', 'FIR_Sync/1');
    
    % Cong thuc 2: Nang luong tuc thoi e[n] = u^2[n]
    add_block('simulink/Math Operations/Math Function', [sb, '/Square'], ...
        'Position', [100, 120, 130, 150], 'Operator', 'square');
    add_line(sb, 'in/1', 'Square/1');
    
    % Cong thuc 3: Cong suat cuc bo P_local[n] = (1/W_pow) * sum(e[n-k])
    add_block('dsparch4/Discrete FIR Filter', [sb, '/MovMean_Pow'], ...
        'Position', [160, 115, 240, 155], ...
        'Coefficients', sprintf('b_pow_%d', i));
    add_line(sb, 'Square/1', 'MovMean_Pow/1');
    
    % Cong thuc 4: Chống chia cho 0 P_safe[n] = max(P_local[n], 1e-12)
    add_block('simulink/Commonly Used Blocks/Saturation', [sb, '/Sat_Floor'], ...
        'Position', [260, 120, 290, 150], ...
        'LowerLimit', 'realmin', 'UpperLimit', 'inf');
    add_line(sb, 'MovMean_Pow/1', 'Sat_Floor/1');
    
    % Cong thuc 5: Cong suat nhieu dac trung P_n
    add_block('simulink/Sources/Constant', [sb, '/Pn'], ...
        'Position', [260, 170, 320, 190], ...
        'Value', sprintf('Pn_%d', i));
    
    % Cong thuc 6: Ty so R[n] = P_n / P_safe[n]
    add_block('simulink/Math Operations/Divide', [sb, '/Div'], ...
        'Position', [340, 125, 370, 160], 'Inputs', '*/');
    add_line(sb, 'Pn/1', 'Div/1');
    add_line(sb, 'Sat_Floor/1', 'Div/2');
    
    % Cong thuc 7: G[n] = 1.0 - R[n] (Constant 1.0 ket hop Subtract +-)
    add_block('simulink/Sources/Constant', [sb, '/Const_1'], ...
        'Position', [390, 95, 420, 115], 'Value', '1.0');
    add_block('simulink/Math Operations/Subtract', [sb, '/Subtract'], ...
        'Position', [440, 115, 470, 150], 'Inputs', '+-');
    add_line(sb, 'Const_1/1', 'Subtract/1');
    add_line(sb, 'Div/1', 'Subtract/2');
    
    % Cong thuc 8: San Gain chong musical noise: clip(G[n], Gain_Floor, 1.0)
    add_block('simulink/Commonly Used Blocks/Saturation', [sb, '/Sat_Gain'], ...
        'Position', [500, 120, 530, 145], ...
        'LowerLimit', 'Gain_Floor', 'UpperLimit', '1.0');
    add_line(sb, 'Subtract/1', 'Sat_Gain/1');
    
    % Cong thuc 9: Lam muot he so: G_smooth[n] = (1/W_sm) * sum(G_clip[n-k])
    add_block('dsparch4/Discrete FIR Filter', [sb, '/MovMean_Sm'], ...
        'Position', [550, 115, 630, 150], ...
        'Coefficients', sprintf('b_sm_%d', i));
    add_line(sb, 'Sat_Gain/1', 'MovMean_Sm/1');
    
    % Cong thuc 10: Nhan loc he so Wavelet: u_out[n] = u_delayed[n] * G_smooth[n]
    add_block('simulink/Math Operations/Product', [sb, '/Mult'], ...
        'Position', [660, 55, 690, 85]);
    add_line(sb, 'FIR_Sync/1', 'Mult/1');
    add_line(sb, 'MovMean_Sm/1', 'Mult/2');
    add_line(sb, 'Mult/1', 'out/1');
    
    % Ket noi DWT vao Subband_i
    add_line(subsys, sprintf('DWT/%d', i), sprintf('Subband_%d/1', i));
    
    % Cong thuc 11: Can bang trê pha tren cay IDWT (Discrete FIR Filter)
    del_name = sprintf('Tree_FIR_%d', i);
    add_block('dsparch4/Discrete FIR Filter', [subsys, '/', del_name], ...
        'Position', [420, 42 + (i-1)*45, 510, 78 + (i-1)*45], ...
        'Coefficients', sprintf('b_tree_%d', i));
    add_line(subsys, sprintf('Subband_%d/1', i), sprintf('%s/1', del_name));
    add_line(subsys, sprintf('%s/1', del_name), sprintf('IDWT/%d', i));
end

% Cong thuc 12: Chong clipping bien do [-1.0, 1.0]
add_block('simulink/Commonly Used Blocks/Saturation', [subsys, '/Sat_Clip'], ...
    'Position', [790, 195, 820, 235], ...
    'LowerLimit', '-1.0', 'UpperLimit', '1.0');
add_line(subsys, 'IDWT/1', 'Sat_Clip/1');
add_line(subsys, 'Sat_Clip/1', 'y_out/1');

% 4. Bo dong bo tre theo cua so cong suat va lam muot da chon
add_block('dsparch4/Discrete FIR Filter', [modelName, '/FIR_Visual_Sync'], ...
    'Position', [340, 180, 420, 210], ...
    'Coefficients', '[zeros(1, Total_Delay), 1]');

add_block('dsparch4/Discrete FIR Filter', [modelName, '/FIR_Clean_Sync'], ...
    'Position', [340, 325, 420, 355], ...
    'Coefficients', '[zeros(1, Total_Delay), 1]');

% 6. To Multimedia File (Xuat file denoised)
snkBlock = [modelName, '/To_Audio_File'];
add_block('dspsnks4/To Multimedia File', snkBlock, ...
    'Position', [700, 80, 870, 130], ...
    'outputFilename', output_audio_file, ...
    'fileType', 'WAV', 'audioDatatype', '24-bit integer');

% 7. CAI TIEN 2: Ghep kenh quan sat 2 kenh (Clean vs Denoised)
concatBlock = [modelName, '/Mux'];
add_block('simulink/Math Operations/Matrix Concatenate', concatBlock, ...
    'Position', [610, 160, 650, 210], ...
    'NumInputs', '2', 'Mode', 'Multidimensional array', 'ConcatenateDimension', '2');

scopeBlock = [modelName, '/Time_Scope_Waveform'];
add_block(sprintf('dspsnks4/Time\nScope'), scopeBlock, ...
    'Position', [860, 150, 930, 195]);

% 8. CAI TIEN 1: Subsystem Bo do chi so Live SNR (In, Out, Delta) & RMSE
meter_sys = [modelName, '/Bo_Do_Chi_So_Hieu_Nang'];
add_block('simulink/Ports & Subsystems/Subsystem', meter_sys, ...
    'Position', [490, 250, 680, 380]);
Simulink.SubSystem.deleteContents(meter_sys);

build_meter(meter_sys, N_frame);

% 9. Cac khoi Display hien thi chi so truc tiep tren canvas Simulink
add_block('simulink/Sinks/Display', [modelName, '/Display_SNR_In'], ...
    'Position', [720, 245, 820, 275], 'Format', 'short');
add_block('simulink/Sinks/Display', [modelName, '/Display_SNR_Out'], ...
    'Position', [720, 285, 820, 315], 'Format', 'short');
add_block('simulink/Sinks/Display', [modelName, '/Display_Delta_SNR'], ...
    'Position', [720, 325, 820, 355], 'Format', 'short');
add_block('simulink/Sinks/Display', [modelName, '/Display_RMSE'], ...
    'Position', [720, 365, 820, 395], 'Format', 'short');

% 10. Ket noi day ngoai vi toan he thong
% Nguon am thanh -> Bo loc Wavelet & FIR Visual Sync
add_line(modelName, 'Noisy/1', 'Bo_Loc_Wavelet_DWT_Wiener/1');
add_line(modelName, 'Noisy/1', 'FIR_Visual_Sync/1');

% Nguon sach -> FIR Clean Sync
add_line(modelName, 'Clean/1', 'FIR_Clean_Sync/1');

add_line(modelName, 'Bo_Loc_Wavelet_DWT_Wiener/1', 'To_Audio_File/1');

% Ghep kenh quan sat Time Scope
add_line(modelName, 'FIR_Clean_Sync/1', 'Mux/1');
add_line(modelName, 'Bo_Loc_Wavelet_DWT_Wiener/1', 'Mux/2');
add_line(modelName, 'Mux/1', 'Time_Scope_Waveform/1');

% Bo do chi so Live SNR / RMSE
add_line(modelName, 'FIR_Clean_Sync/1', 'Bo_Do_Chi_So_Hieu_Nang/1');
add_line(modelName, 'FIR_Visual_Sync/1', 'Bo_Do_Chi_So_Hieu_Nang/2');
add_line(modelName, 'Bo_Loc_Wavelet_DWT_Wiener/1', 'Bo_Do_Chi_So_Hieu_Nang/3');

% Bo do chi so -> Cac khoi Display tren man hinh
add_line(modelName, 'Bo_Do_Chi_So_Hieu_Nang/1', 'Display_SNR_In/1');
add_line(modelName, 'Bo_Do_Chi_So_Hieu_Nang/2', 'Display_SNR_Out/1');
add_line(modelName, 'Bo_Do_Chi_So_Hieu_Nang/3', 'Display_Delta_SNR/1');
add_line(modelName, 'Bo_Do_Chi_So_Hieu_Nang/4', 'Display_RMSE/1');

% Kiem tra nghiem ngat:
% 1. Khong cho phep ton tai khoi MATLAB Function
mf_blocks = find_system(modelName, 'LookUnderMasks', 'all', 'BlockType', 'MATLAB Function');
sfun_eml = find_system(modelName, 'LookUnderMasks', 'all', 'BlockType', 'S-Function', 'FunctionName', 'sf_sfun');
if ~isempty(mf_blocks) || ~isempty(sfun_eml)
    error('WaveletDSP:ForbiddenBlock', 'Phát hiện khối hàm MATLAB trong mô hình!');
end

% 2. Khong cho phep ton tai khoi Delay (z^-A)
delay_blocks = find_system(modelName, 'LookUnderMasks', 'all', 'RegExp', 'on', 'BlockType', '.*Delay.*');
if ~isempty(delay_blocks)
    error('WaveletDSP:DelayFound', 'Phát hiện khối trễ z^-A trong mô hình!');
end

for bandIndex = 1:8
    bandSystem = sprintf('%s/Subband_%d', subsys, bandIndex);
    firNames = {'FIR_Sync', 'MovMean_Pow', 'MovMean_Sm'};
    for filterIndex = 1:numel(firNames)
        set_param([bandSystem '/' firNames{filterIndex}], ...
            'InputProcessing', 'Columns as channels (frame based)');
    end
    set_param(sprintf('%s/Tree_FIR_%d', subsys, bandIndex), ...
        'InputProcessing', 'Columns as channels (frame based)');
end
set_param([modelName '/FIR_Visual_Sync'], 'InputProcessing', 'Columns as channels (frame based)');
set_param([modelName '/FIR_Clean_Sync'], 'InputProcessing', 'Columns as channels (frame based)');
set_param(modelName, 'ReturnWorkspaceOutputs', 'on');
configure_optional_reference(modelName);
configure_noise_profile(modelName);
simplify_meter(modelName);
vietnamese_labels(modelName,false);
configure_numeric_interface(modelName);
save_system(modelName, fullfile(modelFolder, [modelName '.slx']));
fprintf('Đã tạo mô hình %s.slx; không cần chạy tệp lệnh bên ngoài.\n', modelName);
end

function code = model_initialization()
code = strjoin({ ...
    'model = bdroot;', ...
    role_lookup('source','source','model'), ...
    role_lookup('cleanSource','clean','model'), ...
    role_lookup('sink','sink','model'), ...
    role_lookup('filterBlock','filter','model'), ...
    role_lookup('referenceSync','reference_sync','model'), ...
    role_lookup('noisySync','noisy_sync','model'), ...
    'workspace = get_param(model,''ModelWorkspace'');', ...
    'assignin(workspace,''Export_Complete'',false);', ...
    'inputFile = get_param(source,''inputFilename'');', ...
    'inputInfo = audioinfo(inputFile);', ...
    'assert(inputInfo.NumChannels==1,''Only mono input is supported.'');', ...
    'useClean = strcmp(get_param(filterBlock,''Use_Clean''),''1'');', ...
    'cleanFile = get_param(cleanSource,''inputFilename'');', ...
    'if useClean && strcmp(get_param(filterBlock,''Auto_Clean''),''1'')', ...
    '    [inputFolder,inputStem] = fileparts(inputFile);', ...
    '    recordId = regexp(inputStem,''^(speech_\d+)_'',''tokens'',''once'');', ...
    '    assert(~isempty(recordId),''Cannot infer clean; disable Auto_Clean and select Clean directly.'');', ...
    '    cleanFile = fullfile(fileparts(fileparts(inputFolder)),''clean'',[recordId{1} ''.wav'']);', ...
    'end', ...
    'frameSize = str2double(get_param(source,''SamplesPerFrame''));', ...
